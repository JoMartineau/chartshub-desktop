function checkedUrl(input, hosts) {
  let url; try { url = new URL(input); } catch { throw safe('Adresse de téléchargement ReShade invalide.'); }
  if (url.protocol !== 'https:' || !hosts.includes(url.hostname) || url.username || url.password || (url.port && url.port !== '443') || url.hash) throw safe('La redirection du téléchargement ReShade n’est pas autorisée.');
  return url;
}

// URLs and digests are owned by this module; callers cannot supply another executable.
function fetchPinned(url, expectedHash, { hosts, maxBytes, expectedSize, timeoutMs = 45000, label, onProgress, signal }) {
  return new Promise((resolve, reject) => {
    if (signal?.aborted) return reject(cancelled());
    let request, response, timer, settled = false, redirects = 0;
    const finish = (error, bytes) => {
      if (settled) return;
      settled = true; clearTimeout(timer); signal?.removeEventListener('abort', abort);
      response?.destroy(); request?.destroy();
      if (error) reject(error); else resolve(bytes);
    };
    const abort = () => finish(cancelled());
    const progress = (received, total) => { if (typeof onProgress === 'function') onProgress({ label, received, total }); };
    const visit = input => {
      let address; try { address = checkedUrl(input, hosts); } catch (error) { finish(error); return; }
      let active;
      try {
        active = https.request(address, { method: 'GET', headers: { 'User-Agent': 'ChartsHub-ReShade-Installer/1', 'Accept-Encoding': 'identity' } }, incoming => {
          if (settled || active !== request) { incoming.destroy(); return; }
          response = incoming;
          const code = incoming.statusCode;
          if ([301, 302, 303, 307, 308].includes(code)) {
            const location = incoming.headers.location;
            incoming.destroy(); response = null;
            if (++redirects > 3 || typeof location !== 'string' || location.length > 2048) return finish(safe('Trop de redirections pendant le téléchargement ReShade.'));
            let next; try { next = new URL(location, address); } catch { return finish(safe('Adresse de téléchargement ReShade invalide.')); }
            visit(next); return;
          }
          if (code !== 200) return finish(safe('Le téléchargement officiel ReShade est indisponible. Réessayez plus tard.'));
          const encoding = incoming.headers['content-encoding'];
          if (encoding && encoding !== 'identity') return finish(safe('Le téléchargement ReShade utilise un encodage inattendu.'));
          const headerLength = incoming.headers['content-length'];
          const length = headerLength === undefined ? null : /^\d+$/.test(headerLength) ? Number(headerLength) : NaN;
          if (length !== null && (!Number.isSafeInteger(length) || length > maxBytes || (expectedSize !== undefined && length !== expectedSize))) return finish(safe('La taille du téléchargement ReShade est invalide.'));
          const chunks = []; let received = 0;
          try { progress(0, length ?? expectedSize ?? null); } catch { return finish(safe('Le suivi du téléchargement ReShade a échoué.')); }
          incoming.on('data', chunk => {
            if (settled) return;
            received += chunk.length;
            if (received > maxBytes || (expectedSize !== undefined && received > expectedSize)) return finish(safe('Le téléchargement ReShade dépasse la taille autorisée.'));
            chunks.push(chunk);
            try { progress(received, length ?? expectedSize ?? null); } catch { finish(safe('Le suivi du téléchargement ReShade a échoué.')); }
          });
          incoming.once('error', () => finish(safe('La connexion de téléchargement ReShade a été interrompue.')));
          incoming.once('aborted', () => finish(safe('Le téléchargement ReShade est incomplet.')));
          incoming.once('end', () => {
            if (settled) return;
            if ((length !== null && received !== length) || (expectedSize !== undefined && received !== expectedSize)) return finish(safe('Le téléchargement ReShade est incomplet.'));
            const bytes = Buffer.concat(chunks, received);
            if (digest(bytes) !== expectedHash) return finish(safe('Le fichier ReShade téléchargé ne correspond pas à la version vérifiée.'));
            finish(null, bytes);
          });
        });
        request = active;
        active.once('error', () => { if (active === request) finish(safe('Impossible de joindre le téléchargement officiel ReShade.')); });
        active.setTimeout(12000, () => { if (active === request) finish(safe('Le téléchargement ReShade a dépassé le délai autorisé.')); });
        active.end();
      } catch { finish(safe('Impossible de démarrer le téléchargement ReShade.')); }
    };
    signal?.addEventListener('abort', abort, { once: true });
    timer = setTimeout(() => finish(safe('Le téléchargement ReShade a dépassé le délai autorisé.')), timeoutMs);
    visit(url);
  });
}

const CRC_TABLE = Array.from({ length: 256 }, (_, index) => {
  let value = index; for (let bit = 0; bit < 8; bit++) value = (value >>> 1) ^ ((value & 1) ? 0xedb88320 : 0);
  return value >>> 0;
});
function crc32(bytes) { let value = 0xffffffff; for (const byte of bytes) value = CRC_TABLE[(value ^ byte) & 255] ^ (value >>> 8); return (value ^ 0xffffffff) >>> 0; }
function requireRange(bytes, offset, count, end = bytes.length) {
  if (!Number.isSafeInteger(offset) || !Number.isSafeInteger(count) || offset < 0 || count < 0 || offset + count > end || end > bytes.length) throw safe('L’archive ReShade est tronquée ou invalide.');
}
function peHeader(bytes) {
  requireRange(bytes, 0, 64);
  if (bytes.toString('ascii', 0, 2) !== 'MZ') throw safe('Le fichier ReShade n’est pas un programme Windows valide.');
  const header = bytes.readUInt32LE(0x3c); requireRange(bytes, header, 26);
  if (header < 64 || bytes.readUInt32LE(header) !== 0x00004550) throw safe('L’en-tête Windows ReShade est invalide.');
  const optionalSize = bytes.readUInt16LE(header + 20); requireRange(bytes, header + 24, optionalSize);
  return { header, optional: header + 24, optionalSize, magic: bytes.readUInt16LE(header + 24) };
}

// The pinned official setup appends ZIP data on a 512-byte boundary. Its
// Authenticode certificate follows the ZIP; do not mistake that suffix for ZIP data.
function extractRuntime(setup) {
  if (!Buffer.isBuffer(setup) || setup.length > MAX_SETUP_BYTES) throw safe('L’archive ReShade est invalide ou trop volumineuse.');
  const pe = peHeader(setup);
  const directoryOffset = pe.magic === 0x10b ? 96 : pe.magic === 0x20b ? 112 : -1;
  if (directoryOffset < 0 || pe.optionalSize < directoryOffset + 40) throw safe('L’en-tête du programme d’installation ReShade est invalide.');
  const security = pe.optional + directoryOffset + 32;
  const certificateOffset = setup.readUInt32LE(security), certificateSize = setup.readUInt32LE(security + 4);
  let zipEnd = setup.length;
  if (certificateOffset || certificateSize) {
    requireRange(setup, certificateOffset, certificateSize);
    if (!certificateOffset || certificateOffset % 8 || certificateSize < 8 || certificateOffset + certificateSize !== setup.length || setup.readUInt32LE(certificateOffset) < 8 || setup.readUInt32LE(certificateOffset) > certificateSize) throw safe('Le certificat du programme ReShade est invalide.');
    zipEnd = certificateOffset;
  }
  let eocd = -1;
  for (let offset = zipEnd - 22; offset >= Math.max(0, zipEnd - 65564); offset--) {
    if (setup.readUInt32LE(offset) !== 0x06054b50) continue;
    const end = offset + 22 + setup.readUInt16LE(offset + 20);
    const padding = zipEnd - end;
    if (padding < 0 || padding > (certificateSize ? 7 : 0)) continue;
    if (!setup.subarray(end, zipEnd).every(byte => byte === 0)) continue;
    eocd = offset; break;
  }
  if (eocd < 0) throw safe('L’archive intégrée ReShade est introuvable.');
  const entries = setup.readUInt16LE(eocd + 10), centralSize = setup.readUInt32LE(eocd + 12), centralOffset = setup.readUInt32LE(eocd + 16);
  if (setup.readUInt16LE(eocd + 4) || setup.readUInt16LE(eocd + 6) || setup.readUInt16LE(eocd + 8) !== entries || entries < 2 || entries > 32 || centralOffset === 0xffffffff || centralSize === 0xffffffff) throw safe('Le format ZIP du programme ReShade n’est pas pris en charge.');
  const base = eocd - centralSize - centralOffset, central = base + centralOffset;
  requireRange(setup, base, 30, eocd);
  if (base % 512 || setup.readUInt32LE(base) !== 0x04034b50) throw safe('Le début de l’archive ReShade est invalide.');
  requireRange(setup, central, centralSize, eocd);
  let cursor = central, selected = null; const names = new Set(), intervals = [];
  for (let index = 0; index < entries; index++) {
    requireRange(setup, cursor, 46, eocd);
    if (setup.readUInt32LE(cursor) !== 0x02014b50) throw safe('L’index de l’archive ReShade est invalide.');
    const flags = setup.readUInt16LE(cursor + 8), method = setup.readUInt16LE(cursor + 10), crc = setup.readUInt32LE(cursor + 16);
    const compressed = setup.readUInt32LE(cursor + 20), size = setup.readUInt32LE(cursor + 24);
    const nameSize = setup.readUInt16LE(cursor + 28), extraSize = setup.readUInt16LE(cursor + 30), commentSize = setup.readUInt16LE(cursor + 32);
    const local = base + setup.readUInt32LE(cursor + 42);
    requireRange(setup, cursor + 46, nameSize + extraSize + commentSize, eocd);
    const name = setup.toString('utf8', cursor + 46, cursor + 46 + nameSize);
    if (!nameSize || nameSize > 128 || names.has(name) || !/^[A-Za-z0-9_.-]+$/.test(name) || setup.readUInt16LE(cursor + 34) || flags & ~0x0800 || ![0, 8].includes(method) || size > MAX_DLL_BYTES || compressed > MAX_SETUP_BYTES) throw safe('Une entrée de l’archive ReShade est invalide.');
    names.add(name);
    requireRange(setup, local, 30, central);
    if (local < base || setup.readUInt32LE(local) !== 0x04034b50 || setup.readUInt16LE(local + 6) !== flags || setup.readUInt16LE(local + 8) !== method || setup.readUInt32LE(local + 14) !== crc || setup.readUInt32LE(local + 18) !== compressed || setup.readUInt32LE(local + 22) !== size) throw safe('Les en-têtes ZIP ReShade ne correspondent pas.');
    const localNameSize = setup.readUInt16LE(local + 26), localExtra = setup.readUInt16LE(local + 28);
    requireRange(setup, local + 30, localNameSize + localExtra, central);
    if (localNameSize !== nameSize || !setup.subarray(local + 30, local + 30 + localNameSize).equals(setup.subarray(cursor + 46, cursor + 46 + nameSize))) throw safe('Le nom du module ReShade est incohérent.');
    const dataOffset = local + 30 + localNameSize + localExtra;
    requireRange(setup, dataOffset, compressed, central);
    if (intervals.some(([start, end]) => local < end && dataOffset + compressed > start)) throw safe('Les entrées ZIP ReShade se chevauchent.');
    intervals.push([local, dataOffset + compressed]);
    if (name === 'ReShade64.dll') selected = { dataOffset, compressed, size, crc, method };
    cursor += 46 + nameSize + extraSize + commentSize;
  }
  if (cursor !== eocd || !names.has('ReShade32.dll') || !selected || selected.size < 256) throw safe('Le programme d’installation ne contient pas le moteur ReShade attendu.');
  let dll;
  try {
    const compressed = setup.subarray(selected.dataOffset, selected.dataOffset + selected.compressed);
    if (selected.method === 0) dll = Buffer.from(compressed);
    else {
      const result = inflateRawSync(compressed, { maxOutputLength: selected.size, info: true });
      if (result.engine.bytesWritten !== compressed.length) throw Error('Trailing compressed bytes');
      dll = result.buffer;
    }
  } catch { throw safe('Le moteur ReShade ne peut pas être décompressé.'); }
  if (dll.length !== selected.size || crc32(dll) !== selected.crc) throw safe('Le moteur ReShade extrait est endommagé.');
  const image = peHeader(dll);
  if (dll.readUInt16LE(image.header + 4) !== 0x8664 || image.magic !== 0x20b || !(dll.readUInt16LE(image.header + 22) & 0x2000) || !dll.includes(Buffer.from('ReShadeRegisterAddon'))) throw safe('Le moteur extrait n’est pas ReShade Windows 64 bits avec add-ons.');
  return dll;
}

async function downloadRuntime({ onProgress, signal } = {}) {
  const setup = await fetchPinned(SETUP_URL, SETUP_SHA256, { hosts: ['reshade.me', 'www.reshade.me'], maxBytes: MAX_SETUP_BYTES,
    expectedSize: SETUP_BYTES, label: 'Téléchargement de ReShade ' + RUNTIME_VERSION, onProgress, signal });
  if (signal?.aborted) throw cancelled();
  const dll = extractRuntime(setup);
  if (digest(dll) !== RUNTIME_SHA256) throw safe('Le moteur ReShade ne correspond pas à la version vérifiée.');
  return dll;
}

async function downloadStarterEffects({ onProgress, signal } = {}) {
  if (signal?.aborted) throw cancelled();
  const controller = new AbortController(), abort = () => controller.abort();
  signal?.addEventListener('abort', abort, { once: true });
  let timedOut = false;
  const timeout = setTimeout(() => { timedOut = true; abort(); }, 90000);
  try {
    const files = [];
    for (const [relativePath, url, sha256] of STARTER_FILES) {
      let bytes = await fetchPinned(url, sha256, { hosts: ['raw.githubusercontent.com'], maxBytes: 256 * 1024, timeoutMs: 20000,
        label: 'Téléchargement de ' + relativePath.split('/').pop(), onProgress, signal: controller.signal });
      // ReShade searches include directories globally. Give every header its own
      // name so this small pack cannot replace another shader pack's headers.
      // Transform only active include directives, after verifying upstream bytes.
      if (/\.fxh?$/.test(relativePath)) bytes = Buffer.from(bytes.toString('utf8').replace(
        /^([ \t]*#[ \t]*include[ \t]+")([^"\r\n]+)(")/gm,
        (directive, opening, name, closing) => STARTER_HEADERS[name] ? opening + STARTER_HEADERS[name] + closing : directive));
      files.push({ relativePath: PREFIX + relativePath, bytes });
    }
    if (controller.signal.aborted) throw cancelled();
    files.push({ relativePath: PREFIX + 'Shaders/ChartsHub_ReShadeUI.fxh', bytes: Buffer.from(UI_HELPER) });
    const provenance = 'ChartsHub starter effects: Curves, MagicHDR, Technicolor2\n\nChartsHub_ReShadeUI.fxh is an original ChartsHub compatibility helper, not the upstream ReShadeUI.fxh.\nChartsHub_ReShade.fxh: CC0, original notice retained in the file.\nMagicHDR and FXShaders headers: MIT, Lucas Melo (2017); see Licenses/FXShaders.txt.\nCurves and Technicolor2: MIT, CeeJayDK (2014); see Licenses/SweetFX.txt. Original author credits remain in each shader.\n\nLocal changes: downloaded shader/header filenames use the ChartsHub_ prefix. After checking the original SHA-256, only active #include directives in .fx and .fxh files are renamed to the prefixed headers. Shader logic and copyright notices are unchanged.\n\nSources and original upstream SHA-256 checksums (before include renaming):\n' + STARTER_FILES.map(([name, url, checksum]) => `${name}\n${url}\nSHA-256: ${checksum}\n`).join('\n');
    files.push({ relativePath: PREFIX + 'Licenses/SOURCES.txt', bytes: Buffer.from(provenance) });
    return files;
  } catch (error) {
    if (timedOut) throw safe('Le téléchargement des effets a dépassé le délai autorisé.');
    throw error;
  } finally { clearTimeout(timeout); signal?.removeEventListener('abort', abort); }
}

