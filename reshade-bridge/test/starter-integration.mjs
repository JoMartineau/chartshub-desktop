import fs from 'node:fs/promises';
import path from 'node:path';
import assert from 'node:assert/strict';
import {spawn} from 'node:child_process';
import {fileURLToPath} from 'node:url';
import {createRequire} from 'node:module';

const require=createRequire(import.meta.url);
const {pipeRequest}=require('../../companion/reshade-service.cjs');
const {downloadStarterEffects,extractRuntime}=require('../../companion/reshade-downloads.cjs');
const root=path.dirname(path.dirname(fileURLToPath(import.meta.url)));
const runtime=path.join(root,'test/runtime-starter');
const shaderDirectory=path.join(runtime,'ChartsHub-ReShade-Shaders/Shaders');
const pause=ms=>new Promise(resolve=>setTimeout(resolve,ms));
const helper='// Generated by ChartsHub: minimal annotations for the starter effects.\n#pragma once\n#define __UNIFORM_SLIDER_FLOAT1 ui_type = "slider";\n#define __UNIFORM_SLIDER_FLOAT2 ui_type = "slider";\n#define __UNIFORM_SLIDER_INT1 ui_type = "slider";\n';

await fs.mkdir(shaderDirectory,{recursive:true});
// Remove only obsolete, known files from this test's own scratch directory.
assert.equal(path.dirname(path.dirname(shaderDirectory)),runtime);
for(const name of ['ArcaneBloom.fxh','ReShade.fxh','ReShadeUI.fxh'])await fs.unlink(path.join(shaderDirectory,name)).catch(error=>{if(error.code!=='ENOENT')throw error;});
for(const {relativePath,bytes} of await downloadStarterEffects()){
  const target=path.join(runtime,relativePath);
  await fs.mkdir(path.dirname(target),{recursive:true});await fs.writeFile(target,bytes);
}
for(const file of ['ChartsHubReShade.addon64','chartshub-reshade-test.exe'])await fs.copyFile(path.join(root,'bin',file),path.join(runtime,file));
// Extract the official setup in scratch; no writes or launches in the game directory.
const setup=await fs.readFile(process.env.CHARTSHUB_RESHADE_SETUP||path.join(root,'../../ReShade_Setup_6.8.0_Addon.exe'));
await fs.writeFile(path.join(runtime,'dxgi.dll'),extractRuntime(setup));
assert.equal(await fs.readFile(path.join(shaderDirectory,'ChartsHub_ReShadeUI.fxh'),'utf8'),helper);
// Existing packages may keep their common headers above each effect's own folder.
// ReShade sorts global include paths alphabetically, so generic starter headers
// would take precedence over these legacy headers and break unrelated shaders.
const existingDirectory=path.join(runtime,'reshade-shaders/Shaders');
await fs.mkdir(path.join(existingDirectory,'ExistingPack'),{recursive:true});
await fs.writeFile(path.join(existingDirectory,'ReShadeUI.fxh'),'#pragma once\n#define __UNIFORM_COLOR_FLOAT3 ui_type = "color";\n');
await fs.writeFile(path.join(existingDirectory,'ReShade.fxh'),'#pragma once\n#define EXISTING_PACKAGE_SENTINEL 314\n');
await fs.writeFile(path.join(existingDirectory,'ExistingPack/ExistingPackProbe.fx'),`
#include "ReShadeUI.fxh"
#include "ReShade.fxh"
#if EXISTING_PACKAGE_SENTINEL != 314
#error Wrong existing package common header
#endif
uniform float3 ExistingColor < __UNIFORM_COLOR_FLOAT3 > = float3(.2,.3,.4);
void VS(uint id : SV_VertexID, out float4 position : SV_Position, out float2 uv : TEXCOORD) {
  uv=float2((id==2)?2.0:0.0,(id==1)?2.0:0.0);position=float4(uv*float2(2,-2)+float2(-1,1),0,1);
}
float4 PS(float4 position : SV_Position,float2 uv : TEXCOORD) : SV_Target {return float4(ExistingColor,1);}
technique ExistingPackProbe { pass { VertexShader=VS; PixelShader=PS; } }
`);
await fs.writeFile(path.join(shaderDirectory,'ChartsHubStarterInput.fx'),`
uniform bool Spot = true;
texture2D Input : COLOR;
sampler2D InputSampler { Texture = Input; };
void VS(uint id : SV_VertexID, out float4 position : SV_Position, out float2 uv : TEXCOORD) {
  uv=float2((id==2)?2.0:0.0,(id==1)?2.0:0.0);
  position=float4(uv*float2(2,-2)+float2(-1,1),0,1);
}
float4 PS(float4 position : SV_Position,float2 uv : TEXCOORD) : SV_Target {
  bool inside=Spot && all(uv>float2(.55,.42)) && all(uv<float2(.70,.58));
  return float4(inside?float3(1,1,1):float3(0,0,0),1);
}
technique ChartsHubStarterInput { pass { VertexShader=VS; PixelShader=PS; } }
`);
await fs.writeFile(path.join(runtime,'ReShade.ini'),`[ADDON]\nAddonPath=.\\\nDisabledAddons=Generic Depth\n\n[GENERAL]\nCheckForUpdates=0\nEffectSearchPaths=.\\reshade-shaders\\Shaders\\**,.\\ChartsHub-ReShade-Shaders\\Shaders\nTextureSearchPaths=.\\Shaders\nPresetPath=.\\TestPreset.ini\nNoEffectCache=1\nNoDebugInfo=1\nPerformanceMode=0\nSkipLoadingDisabledEffects=0\n\n[OVERLAY]\nAutoSavePreset=0\nTutorialProgress=4\n\n[INPUT]\nKeyOverlay=0,0,0,0\nKeyEffects=0,0,0,0\n`);
await fs.writeFile(path.join(runtime,'TestPreset.ini'),'Techniques=ChartsHubStarterInput@ChartsHubStarterInput.fx\nTechniqueSorting=ChartsHubStarterInput@ChartsHubStarterInput.fx,ArcaneBloom@ChartsHub_ArcaneBloom.fx,FilmGrain@ChartsHub_FilmGrain.fx,CA@ChartsHub_ChromaticAberration.fx\n\n[ChartsHub_ArcaneBloom.fx]\nuAdapt_Intensity=0.000000\nuBloomIntensity=1.000000\nuExposure=1.000000\n');

let processOutput='',stdoutPending='',lastFrame=null,closed=false,checks=0,sequence=0;
const child=spawn(path.join(runtime,'chartshub-reshade-test.exe'),[],{cwd:runtime,windowsHide:true,stdio:['ignore','pipe','pipe']});
child.stdout.setEncoding('utf8');child.stderr.setEncoding('utf8');
child.stdout.on('data',s=>{processOutput+=s;stdoutPending+=s;let at;while((at=stdoutPending.indexOf('\n'))>=0){const line=stdoutPending.slice(0,at);stdoutPending=stdoutPending.slice(at+1);try{const value=JSON.parse(line);if(value.pixel)lastFrame=value;}catch{}}});
child.stderr.on('data',s=>{processOutput+=s;console.log(s.trim());});
child.on('exit',(code,signal)=>{closed=true;processOutput+=`\nExit code=${code} signal=${signal}\n`;});
function check(condition,label){assert.ok(condition,label);checks++;console.log(`PASS: ${label}`);}
async function request(action,extra={}){return pipeRequest(child.pid,{id:++sequence,action,...extra});}
async function pixelCheck(predicate,label){const after=lastFrame?.frame||0;for(let attempt=0;attempt<200;attempt++){if(lastFrame?.frame>after&&predicate(lastFrame.pixel)){check(true,`${label}: ${lastFrame.pixel}`);return [...lastFrame.pixel];}if(closed)throw new Error(processOutput);await pause(25);}check(false,`${label}: observed ${JSON.stringify(lastFrame)}`);}
async function setUniform(effect,name,value){await request('catalog');const metadata=await request('uniforms',{effect});const uniform=metadata.uniforms.find(u=>u.name===name);assert.ok(uniform,`${effect}: missing ${name}`);await request('setUniform',{uniformId:uniform.id,value:[value]});}
async function setTechnique(effect,enabled){const catalog=await request('catalog');const technique=catalog.techniques.find(t=>t.effect===effect);assert.ok(technique,`Missing ${effect}`);await request('setTechnique',{techniqueId:technique.id,enabled});}

try{
  let catalog;
  for(let attempt=0;attempt<120;attempt++){
    if(closed)throw new Error(processOutput);
    try{const status=await request('status');if(status.runtimeReady){catalog=await request('catalog');if(catalog.techniques.length===5)break;}}catch{}
    await pause(200);
  }
  for(const [name,effect] of [['ArcaneBloom','ChartsHub_ArcaneBloom.fx'],['FilmGrain','ChartsHub_FilmGrain.fx'],['CA','ChartsHub_ChromaticAberration.fx']])check(catalog?.techniques.some(t=>t.name===name&&t.effect===effect),`pinned ${name} source compiles with minimal helper`);
  check(catalog?.techniques.some(t=>t.name==='ExistingPackProbe'),'existing nested shader still resolves its original common and UI headers');
  const existingUniforms=(await request('uniforms',{effect:'ExistingPackProbe.fx'})).uniforms;
  check(existingUniforms.some(u=>u.name==='ExistingColor'&&u.components===3&&u.uiType==='color'),'existing package keeps its color macro and metadata');
  await request('setEnabled',{enabled:true});await pause(1200);
  await pixelCheck(pixel=>pixel.slice(0,3).every(n=>n<=1),'bloom disabled: sample outside bright patch stays black');
  await setTechnique('ChartsHub_ArcaneBloom.fx',true);await pause(2200);
  await request('catalog');
  const bloom=(await request('uniforms',{effect:'ChartsHub_ArcaneBloom.fx'})).uniforms;
  check(bloom.some(u=>u.name==='uBloomIntensity'&&u.type==='float'&&u.min[0]===0&&u.max[0]===100),'ArcaneBloom exposes editable intensity range');
  check(bloom.some(u=>u.name==='uAdapt_Intensity'&&u.value[0]===0),'starter preset suppresses automatic exposure adaptation');
  await setUniform('ChartsHub_ArcaneBloom.fx','uBloomIntensity',0);
  await pixelCheck(pixel=>pixel.slice(0,3).every(n=>n<=1),'zero bloom intensity leaves the black halo sample unchanged');
  await setUniform('ChartsHub_ArcaneBloom.fx','uBloomIntensity',1);
  const low=await pixelCheck(pixel=>pixel[0]>1,'bloom produces visible halo outside bright source');
  await setUniform('ChartsHub_ArcaneBloom.fx','uBloomIntensity',10);
  const high=await pixelCheck(pixel=>pixel[0]>low[0]+3,'live intensity control increases actual GPU halo');
  check(high[3]===255,'bloom output remains opaque');
  await setUniform('ChartsHubStarterInput.fx','Spot',false);
  await pixelCheck(pixel=>pixel.slice(0,3).every(n=>n<=1),'no bright source produces no bloom, even at high intensity');
  await setUniform('ChartsHubStarterInput.fx','Spot',true);
  await pixelCheck(pixel=>pixel[0]>low[0]+3,'restoring bright source restores spatial bloom');
  await setTechnique('ChartsHub_ArcaneBloom.fx',false);
  await pixelCheck(pixel=>pixel.slice(0,3).every(n=>n<=1),'disabling ArcaneBloom restores original GPU sample');
  const grain=(await request('uniforms',{effect:'ChartsHub_FilmGrain.fx'})).uniforms;
  check(grain.some(u=>u.name==='Intensity'&&u.min[0]===0&&u.max[0]===1),'minimal helper preserves FilmGrain control metadata');
  const ca=(await request('uniforms',{effect:'ChartsHub_ChromaticAberration.fx'})).uniforms;
  check(ca.some(u=>u.name==='Shift'&&u.components===2&&u.min.every(n=>n===-10)&&u.max.every(n=>n===10)),'minimal helper preserves chromatic vector controls');
  // ReShade saves uniform values only for effects with an enabled technique.
  await setTechnique('ChartsHub_ArcaneBloom.fx',true);
  await request('savePreset');
  let preset='';
  for(let attempt=0;attempt<20;attempt++){preset=await fs.readFile(path.join(runtime,'TestPreset.ini'),'utf8');if(preset.includes('uBloomIntensity=10.000000'))break;await pause(100);}
  check(preset.includes('uBloomIntensity=10.000000')&&preset.includes('uAdapt_Intensity=0.000000'),'official preset save persists starter bloom edits');
  console.log(`SUCCESS: ${checks} starter shader checks; bloom halo red ${low[0]} -> ${high[0]}.`);
}finally{
  child.kill();await pause(300);await fs.writeFile(path.join(root,'test/starter-harness-output.log'),processOutput);
}
